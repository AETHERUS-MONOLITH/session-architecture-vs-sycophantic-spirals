// Copies the self-hosted fonts (SIL OFL 1.1) from the @fontsource npm packages into public/fonts/
// and writes public/fonts/fonts.css. The families and weights are the ones the source page loaded
// from Google Fonts: Newsreader (opsz, 500/600), IBM Plex Sans 400/500/600, IBM Plex Mono 400/500.
// Run: node tools/vendor-fonts.mjs   (output is committed; the build does not need the packages)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const nm = path.join(root, 'node_modules');
const out = path.join(root, 'public', 'fonts');
const SUBSETS = ['latin', 'latin-ext', 'greek'];
const jobs = [
  { pkg: '@fontsource-variable/newsreader', dir: 'newsreader', css: ['opsz.css'], family: 'Newsreader' },
  { pkg: '@fontsource/ibm-plex-sans', dir: 'ibm-plex-sans', css: ['400.css', '500.css', '600.css'], family: 'IBM Plex Sans' },
  { pkg: '@fontsource/ibm-plex-mono', dir: 'ibm-plex-mono', css: ['400.css', '500.css'], family: 'IBM Plex Mono' },
];
fs.rmSync(out, { recursive: true, force: true });
let css = '/* Self-hosted fonts, generated by tools/vendor-fonts.mjs from the @fontsource packages.\n   Licensed under the SIL Open Font License 1.1; see OFL.txt in each family folder (third-party notice, not a project license). */\n';
const notice = [];
for (const j of jobs) {
  const pdir = path.join(nm, j.pkg);
  const version = JSON.parse(fs.readFileSync(path.join(pdir, 'package.json'), 'utf8')).version;
  const fdir = path.join(out, j.dir);
  fs.mkdirSync(fdir, { recursive: true });
  fs.copyFileSync(path.join(pdir, 'LICENSE'), path.join(fdir, 'OFL.txt'));
  notice.push(`${j.family}: npm package ${j.pkg}@${version}, SIL Open Font License 1.1 (${j.dir}/OFL.txt)`);
  for (const file of j.css) {
    const text = fs.readFileSync(path.join(pdir, file), 'utf8');
    const blocks = text.split(/(?=\/\* )/).filter((b) => b.includes('@font-face'));
    for (const b of blocks) {
      const name = b.match(/\/\* (\S+) \*\//)[1];
      if (!SUBSETS.some((s) => name.includes(`-${s}-`))) continue;
      if (name.includes('-latin-ext-') === false && name.includes('-ext-')) continue;
      const woff2 = b.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
      fs.copyFileSync(path.join(pdir, 'files', woff2), path.join(fdir, woff2));
      let block = b
        .replace(/font-family: '[^']+';/, `font-family: '${j.family}';`)
        .replace(/src: [^;]+;/, `src: url(./${j.dir}/${woff2}) format('${woff2.includes('opsz') ? 'woff2-variations' : 'woff2'}');`);
      css += '\n' + block.trim() + '\n';
    }
  }
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
fs.writeFileSync(path.join(out, 'NOTICE.txt'), 'Third-party font notice (not a project license)\n\n' + notice.join('\n') + '\n');
console.log(fs.readdirSync(out, { recursive: true }).join('\n'));
